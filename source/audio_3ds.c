/*
 * Gravepowder - Nintendo 3DS audio backend (libctru ndsp)
 *
 * Implements the portable audio.h contract with the DSP mixer.  All clips are
 * original synthesized mono PCM16 (tools/make_audio.py) linked in from data/
 * by the Makefile's bin2o rule; the generated build/<name>_bin.h headers
 * declare the data arrays and their byte sizes.
 *
 * Channel plan: 0 = looping music, 1..15 = SFX voice pool (round-robin steal).
 * SFX run at 22050 Hz, music at 16000 Hz.  Gunshots get a small random pitch
 * variation and the revolver picks one of three recorded variants; zombie
 * groan/swipe voices are capped so a horde does not turn into a wall of noise.
 *
 * The DSP reads wave buffers from linear memory, so every clip is copied into
 * one linearAlloc block during audio_init(); there is no dynamic allocation
 * after init.  If ndspInit() fails (no DSP1 firmware / no service) the whole
 * module silently disables itself and the game runs normally.
 */
#include <3ds.h>
#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>
#include <string.h>

#include "audio.h"
#include "grave.h"   /* GRAVE_EVT_* bits, WeaponId values */

/* Generated by bin2o; names are <file> with dots replaced by underscores. */
#include "sfx_flintlock_bin.h"
#include "sfx_revolver_1_bin.h"
#include "sfx_revolver_2_bin.h"
#include "sfx_revolver_3_bin.h"
#include "sfx_musket_bin.h"
#include "sfx_reload_flintlock_bin.h"
#include "sfx_reload_revolver_bin.h"
#include "sfx_reload_musket_bin.h"
#include "sfx_empty_click_bin.h"
#include "sfx_hit_thud_bin.h"
#include "sfx_zombie_death_bin.h"
#include "sfx_zombie_attack_bin.h"
#include "sfx_player_hurt_bin.h"
#include "sfx_coin_bin.h"
#include "sfx_squelch_bin.h"
#include "sfx_quest_complete_bin.h"
#include "sfx_zone_clear_bin.h"
#include "sfx_game_over_bin.h"
#include "music_menu_bin.h"
#include "music_zone_bin.h"

#define MUSIC_CHANNEL        0
#define SFX_CHANNEL_FIRST    1
#define SFX_CHANNEL_COUNT    15
#define SFX_CHANNEL_LAST     (SFX_CHANNEL_FIRST + SFX_CHANNEL_COUNT - 1)

#define SFX_RATE             22050.0f
#define MUSIC_RATE           16000.0f
#define LINEAR_ALIGN         64u

/* Too many simultaneous zombie vocalisations = mush; cap the stack. */
#define MAX_GROAN_VOICES     4
/* Every Nth successful hit adds a wet sinew squelch on top of the thud. */
#define HIT_SQUELCH_EVERY    3

enum {
    CLIP_FLINTLOCK = 0,
    CLIP_REVOLVER_1,
    CLIP_REVOLVER_2,
    CLIP_REVOLVER_3,
    CLIP_MUSKET,
    CLIP_RELOAD_FLINTLOCK,
    CLIP_RELOAD_REVOLVER,
    CLIP_RELOAD_MUSKET,
    CLIP_EMPTY_CLICK,
    CLIP_HIT_THUD,
    CLIP_ZOMBIE_DEATH,
    CLIP_ZOMBIE_ATTACK,
    CLIP_PLAYER_HURT,
    CLIP_COIN,
    CLIP_SQUELCH,
    CLIP_QUEST_COMPLETE,
    CLIP_ZONE_CLEAR,
    CLIP_GAME_OVER,
    CLIP_MUSIC_MENU,
    CLIP_MUSIC_ZONE,
    CLIP_COUNT
};

typedef struct {
    const uint8_t *rom;   /* data linked into the .3dsx rodata        */
    size_t         bytes;
    s16           *ram;   /* linearAlloc'd copy the DSP reads         */
    u32            nsamples;
    float          rate;
} AudioClip;

static AudioClip s_clips[CLIP_COUNT];
static ndspWaveBuf s_voice_buf[SFX_CHANNEL_COUNT];
static u8 s_voice_clip[SFX_CHANNEL_COUNT];
static ndspWaveBuf s_music_buf[GRAVE_MUSIC_COUNT];

static s16   *s_linear = NULL;
static bool   s_enabled = false;
static bool   s_muted = false;
static GraveMusic s_current = GRAVE_MUSIC_NONE;
static GraveMusic s_requested = GRAVE_MUSIC_NONE;
static int    s_weapon = WEAPON_FLINTLOCK;
static u32    s_voice_next = 0;
static u32    s_rng = 0x6C8E9CF5u;
static u8     s_hit_counter = 0;

/* ------------------------------------------------------------------------ */
/* helpers                                                                   */
/* ------------------------------------------------------------------------ */

static u32 align_up(u32 value, u32 alignment)
{
    return (value + (alignment - 1u)) & ~(alignment - 1u);
}

static u32 next_random(void)
{
    /* xorshift32; any non-zero state works. */
    s_rng ^= s_rng << 13;
    s_rng ^= s_rng >> 17;
    s_rng ^= s_rng << 5;
    return s_rng;
}

/* Uniform float in [0,1). */
static float random_unit(void)
{
    return (float)(next_random() & 0xFFFFFFu) / 16777216.0f;
}

/* Random pitch multiplier in [1-range, 1+range). */
static float random_pitch(float range)
{
    return 1.0f + (random_unit() * 2.0f - 1.0f) * range;
}

static void clip_set(int index, const uint8_t *rom, size_t bytes, float rate)
{
    AudioClip *clip = &s_clips[index];

    clip->rom = rom;
    clip->bytes = bytes;
    clip->ram = NULL;
    clip->nsamples = 0;
    clip->rate = rate;
    if (bytes >= 2u && (bytes & 1u) == 0u && rate > 0.0f)
        clip->nsamples = (u32)(bytes / 2u);
}

static bool clip_ready(int index)
{
    if (index < 0 || index >= CLIP_COUNT)
        return false;
    return s_clips[index].ram != NULL && s_clips[index].nsamples > 0u;
}

static void channel_setup(int id, u16 format, ndspInterpType interp, float rate)
{
    ndspChnReset(id);
    ndspChnSetFormat(id, format);
    ndspChnSetInterp(id, interp);
    ndspChnSetRate(id, rate);
    ndspChnSetPaused(id, false);
}

/* Find a free voice; if all are busy, steal the next one round-robin. */
static int voice_acquire(void)
{
    int i;

    for (i = 0; i < SFX_CHANNEL_COUNT; i++) {
        int candidate = (int)((s_voice_next + (u32)i) % (u32)SFX_CHANNEL_COUNT);
        u8 status = s_voice_buf[candidate].status;
        if (status == NDSP_WBUF_FREE || status == NDSP_WBUF_DONE) {
            s_voice_next = ((u32)candidate + 1u) % (u32)SFX_CHANNEL_COUNT;
            return candidate;
        }
    }
    i = (int)(s_voice_next % (u32)SFX_CHANNEL_COUNT);
    s_voice_next = ((u32)i + 1u) % (u32)SFX_CHANNEL_COUNT;
    return i;
}

static void play_clip(int clip_index, float rate_scale)
{
    AudioClip *clip;
    ndspWaveBuf *buf;
    int voice;
    int channel;

    if (!clip_ready(clip_index))
        return;
    clip = &s_clips[clip_index];

    voice = voice_acquire();
    channel = SFX_CHANNEL_FIRST + voice;

    buf = &s_voice_buf[voice];
    ndspChnWaveBufClear(channel);
    memset(buf, 0, sizeof(*buf));
    buf->data_pcm16 = clip->ram;
    buf->nsamples = clip->nsamples;
    buf->looping = false;
    buf->status = NDSP_WBUF_FREE;
    ndspChnSetFormat(channel, NDSP_FORMAT_MONO_PCM16);
    ndspChnSetInterp(channel, NDSP_INTERP_NONE);
    ndspChnSetRate(channel, clip->rate * rate_scale);
    ndspChnSetPaused(channel, false);
    ndspChnWaveBufAdd(channel, buf);
    s_voice_clip[voice] = (u8)clip_index;
}

/* Number of zombie vocalisation voices currently queued/playing. */
static int active_groans(void)
{
    int i;
    int count = 0;

    for (i = 0; i < SFX_CHANNEL_COUNT; i++) {
        if (s_voice_clip[i] != (u8)CLIP_ZOMBIE_ATTACK)
            continue;
        if (s_voice_buf[i].status == NDSP_WBUF_QUEUED ||
            s_voice_buf[i].status == NDSP_WBUF_PLAYING)
            count++;
    }
    return count;
}

static void play_groan(void)
{
    if (active_groans() >= MAX_GROAN_VOICES)
        return;
    play_clip(CLIP_ZOMBIE_ATTACK, random_pitch(0.05f));
}

static void play_music_clip(int clip_index)
{
    AudioClip *clip;
    ndspWaveBuf *buf;
    int slot = (clip_index == CLIP_MUSIC_MENU) ? GRAVE_MUSIC_MENU : GRAVE_MUSIC_ZONE;

    if (!clip_ready(clip_index))
        return;
    clip = &s_clips[clip_index];
    buf = &s_music_buf[slot];

    ndspChnWaveBufClear(MUSIC_CHANNEL);
    memset(buf, 0, sizeof(*buf));
    buf->data_pcm16 = clip->ram;
    buf->nsamples = clip->nsamples;
    buf->looping = true;
    buf->status = NDSP_WBUF_FREE;
    ndspChnSetFormat(MUSIC_CHANNEL, NDSP_FORMAT_MONO_PCM16);
    ndspChnSetInterp(MUSIC_CHANNEL, NDSP_INTERP_LINEAR);
    ndspChnSetRate(MUSIC_CHANNEL, clip->rate);
    ndspChnSetPaused(MUSIC_CHANNEL, false);
    ndspChnWaveBufAdd(MUSIC_CHANNEL, buf);
    if (s_muted)
        ndspChnSetPaused(MUSIC_CHANNEL, true);
}

static void sfx_stop_all(void)
{
    int i;

    for (i = SFX_CHANNEL_FIRST; i <= SFX_CHANNEL_LAST; i++) {
        ndspChnWaveBufClear(i);
        ndspChnSetPaused(i, true);
    }
    memset(s_voice_buf, 0, sizeof(s_voice_buf));
    memset(s_voice_clip, 0, sizeof(s_voice_clip));
}

