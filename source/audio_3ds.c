void audio_init(void)
{
    u32 sizes[CLIP_COUNT];
    u32 total = 0;
    u32 offset = 0;
    int i;

    s_enabled = false;
    s_muted = false;
    s_current = GRAVE_MUSIC_NONE;
    s_requested = GRAVE_MUSIC_NONE;
    s_weapon = WEAPON_FLINTLOCK;
    s_voice_next = 0;
    s_rng = 0x6C8E9CF5u;
    s_hit_counter = 0;

    clip_set(CLIP_FLINTLOCK, sfx_flintlock_bin, sfx_flintlock_bin_size, SFX_RATE);
    clip_set(CLIP_REVOLVER_1, sfx_revolver_1_bin, sfx_revolver_1_bin_size, SFX_RATE);
    clip_set(CLIP_REVOLVER_2, sfx_revolver_2_bin, sfx_revolver_2_bin_size, SFX_RATE);
    clip_set(CLIP_REVOLVER_3, sfx_revolver_3_bin, sfx_revolver_3_bin_size, SFX_RATE);
    clip_set(CLIP_MUSKET, sfx_musket_bin, sfx_musket_bin_size, SFX_RATE);
    clip_set(CLIP_RELOAD_FLINTLOCK, sfx_reload_flintlock_bin,
             sfx_reload_flintlock_bin_size, SFX_RATE);
    clip_set(CLIP_RELOAD_REVOLVER, sfx_reload_revolver_bin,
             sfx_reload_revolver_bin_size, SFX_RATE);
    clip_set(CLIP_RELOAD_MUSKET, sfx_reload_musket_bin,
             sfx_reload_musket_bin_size, SFX_RATE);
    clip_set(CLIP_EMPTY_CLICK, sfx_empty_click_bin, sfx_empty_click_bin_size, SFX_RATE);
    clip_set(CLIP_HIT_THUD, sfx_hit_thud_bin, sfx_hit_thud_bin_size, SFX_RATE);
    clip_set(CLIP_ZOMBIE_DEATH, sfx_zombie_death_bin,
             sfx_zombie_death_bin_size, SFX_RATE);
    clip_set(CLIP_ZOMBIE_ATTACK, sfx_zombie_attack_bin,
             sfx_zombie_attack_bin_size, SFX_RATE);
    clip_set(CLIP_PLAYER_HURT, sfx_player_hurt_bin,
             sfx_player_hurt_bin_size, SFX_RATE);
    clip_set(CLIP_COIN, sfx_coin_bin, sfx_coin_bin_size, SFX_RATE);
    clip_set(CLIP_SQUELCH, sfx_squelch_bin, sfx_squelch_bin_size, SFX_RATE);
    clip_set(CLIP_QUEST_COMPLETE, sfx_quest_complete_bin,
             sfx_quest_complete_bin_size, SFX_RATE);
    clip_set(CLIP_ZONE_CLEAR, sfx_zone_clear_bin, sfx_zone_clear_bin_size, SFX_RATE);
    clip_set(CLIP_GAME_OVER, sfx_game_over_bin, sfx_game_over_bin_size, SFX_RATE);
    clip_set(CLIP_MUSIC_MENU, music_menu_bin, music_menu_bin_size, MUSIC_RATE);
    clip_set(CLIP_MUSIC_ZONE, music_zone_bin, music_zone_bin_size, MUSIC_RATE);

    if (ndspInit() != 0) {
        /* No DSP firmware/service: the game runs fine without sound. */
        svcOutputDebugString("Gravepowder audio: ndspInit failed, silent\n", 41);
        return;
    }

    ndspSetOutputMode(NDSP_OUTPUT_STEREO);

    for (i = 0; i < CLIP_COUNT; i++) {
        sizes[i] = align_up((u32)s_clips[i].bytes, LINEAR_ALIGN);
        total += sizes[i];
    }

    if (total == 0u || total > 4u * 1024u * 1024u) {
        ndspExit();
        return;
    }

    s_linear = (s16 *)linearAlloc(total);
    if (s_linear == NULL) {
        ndspExit();
        return;
    }
    memset(s_linear, 0, total);

    for (i = 0; i < CLIP_COUNT; i++) {
        if (s_clips[i].bytes >= 2u && (s_clips[i].bytes & 1u) == 0u) {
            memcpy((u8 *)s_linear + offset, s_clips[i].rom, s_clips[i].bytes);
            s_clips[i].ram = (s16 *)((u8 *)s_linear + offset);
        }
        offset += sizes[i];
    }

    memset(s_music_buf, 0, sizeof(s_music_buf));
    memset(s_voice_buf, 0, sizeof(s_voice_buf));
    memset(s_voice_clip, 0, sizeof(s_voice_clip));

    channel_setup(MUSIC_CHANNEL, NDSP_FORMAT_MONO_PCM16,
                  NDSP_INTERP_LINEAR, MUSIC_RATE);
    for (i = 0; i < SFX_CHANNEL_COUNT; i++)
        channel_setup(SFX_CHANNEL_FIRST + i, NDSP_FORMAT_MONO_PCM16,
                      NDSP_INTERP_NONE, SFX_RATE);

    s_enabled = true;
    svcOutputDebugString("Gravepowder audio: ndsp mixer ready\n", 37);

    if (s_requested != GRAVE_MUSIC_NONE)
        audio_set_music(s_requested);
}

void audio_exit(void)
{
    if (s_enabled) {
        int i;

        for (i = 0; i <= SFX_CHANNEL_LAST; i++) {
            ndspChnWaveBufClear(i);
            ndspChnSetPaused(i, true);
        }
        ndspExit();
        s_enabled = false;
    }
    if (s_linear != NULL) {
        linearFree(s_linear);
        s_linear = NULL;
    }
    s_current = GRAVE_MUSIC_NONE;
    s_requested = GRAVE_MUSIC_NONE;
}

void audio_play_event(uint32_t grave_events)
{
    if (!s_enabled || s_muted || grave_events == 0u)
        return;

    if (grave_events & GRAVE_EVT_SHOOT) {
        switch (s_weapon) {
        case WEAPON_REVOLVER:
            play_clip(CLIP_REVOLVER_1 + (int)(next_random() % 3u),
                      random_pitch(0.055f));
            break;
        case WEAPON_MUSKET:
            play_clip(CLIP_MUSKET, random_pitch(0.04f));
            break;
        case WEAPON_FLINTLOCK:
        default:
            play_clip(CLIP_FLINTLOCK, random_pitch(0.05f));
            break;
        }
    }

    if (grave_events & GRAVE_EVT_RELOAD) {
        switch (s_weapon) {
        case WEAPON_REVOLVER:
            play_clip(CLIP_RELOAD_REVOLVER, random_pitch(0.03f));
            break;
        case WEAPON_MUSKET:
            play_clip(CLIP_RELOAD_MUSKET, random_pitch(0.03f));
            break;
        case WEAPON_FLINTLOCK:
        default:
            play_clip(CLIP_RELOAD_FLINTLOCK, random_pitch(0.03f));
            break;
        }
    }

    if (grave_events & GRAVE_EVT_HIT) {
        play_clip(CLIP_HIT_THUD, random_pitch(0.10f));
        if (++s_hit_counter >= HIT_SQUELCH_EVERY) {
            s_hit_counter = 0;
            play_clip(CLIP_SQUELCH, random_pitch(0.08f));
        }
    }

    if (grave_events & GRAVE_EVT_ZOMBIE_DIE) {
        play_clip(CLIP_ZOMBIE_DEATH, random_pitch(0.06f));
    }

    if (grave_events & GRAVE_EVT_PICKUP)
        play_clip(CLIP_COIN, random_pitch(0.04f));

    if (grave_events & GRAVE_EVT_HURT) {
        play_clip(CLIP_PLAYER_HURT, random_pitch(0.05f));
        if (random_unit() < 0.45f)
            play_groan();
    }

    if (grave_events & GRAVE_EVT_QUEST_DONE)
        play_clip(CLIP_QUEST_COMPLETE, 1.0f);

    if (grave_events & GRAVE_EVT_ZONE_DONE)
        play_clip(CLIP_ZONE_CLEAR, 1.0f);

    if (grave_events & GRAVE_EVT_EMPTY_GUN)
        play_clip(CLIP_EMPTY_CLICK, random_pitch(0.02f));
}

void audio_set_music(GraveMusic track)
{
    if (track != GRAVE_MUSIC_MENU && track != GRAVE_MUSIC_ZONE)
        track = GRAVE_MUSIC_NONE;

    s_requested = track;
    if (!s_enabled)
        return;
    if (track == s_current)
        return;

    s_current = track;
    ndspChnWaveBufClear(MUSIC_CHANNEL);
    if (track == GRAVE_MUSIC_MENU)
        play_music_clip(CLIP_MUSIC_MENU);
    else if (track == GRAVE_MUSIC_ZONE)
        play_music_clip(CLIP_MUSIC_ZONE);
    else
        ndspChnSetPaused(MUSIC_CHANNEL, true);
}

GraveMusic audio_current_music(void)
{
    return s_current;
}

/* Host-preview helpers: meaningless on hardware (see audio.h). */
uint32_t audio_event_history(void)
{
    return 0;
}

uint32_t audio_event_count(void)
{
    return 0;
}

void audio_set_muted(bool muted)
{
    s_muted = muted;
    if (!s_enabled)
        return;

    if (muted) {
        ndspChnSetPaused(MUSIC_CHANNEL, true);
        sfx_stop_all();
    } else {
        ndspChnSetPaused(MUSIC_CHANNEL, false);
        {
            int i;
            for (i = SFX_CHANNEL_FIRST; i <= SFX_CHANNEL_LAST; i++)
                ndspChnSetPaused(i, false);
        }
    }
}

bool audio_is_muted(void)
{
    return s_muted;
}

void audio_set_weapon(int weapon_id)
{
    if (weapon_id < 0)
        weapon_id = 0;
    if (weapon_id > WEAPON_MUSKET)
        weapon_id = WEAPON_MUSKET;
    s_weapon = weapon_id;
}
